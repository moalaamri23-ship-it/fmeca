/** Creation date of a project as ISO 8601 UTC, tolerating the `created`/`createdAt` split. */
export function projectStartIso(project: Project): string {
    const normalized = normalizeProjectDates(project as any);
    return tryIso(normalized.createdAt) || new Date().toISOString();
}

/** `YYYY-MM-DD` for an `<input type="date">`, derived from the project's creation date. */
export function projectStartDateInput(project: Project): string {
    return projectStartIso(project).slice(0, 10);
}

/** Sub-system names, deduped, blanks dropped, source order preserved. */
export function subSystemNames(project: Project): string[] {
    const seen = new Set<string>();
    const names: string[] = [];
    (project.subsystems || []).forEach(s => {
        const name = (s?.name || '').trim();
        if (!name || seen.has(name)) return;
        seen.add(name);
        names.push(name);
    });
    return names;
}

/** Numbered one per line — "1- Pump Assembly" — as the register list expects. */
export function buildSubSystemsList(project: Project): string {
    return subSystemNames(project).map((name, i) => `${i + 1}- ${name}`).join('\n');
}

/** Modes at or above this total are counted as high risk — the red band of the RPN chip. */
export const HIGH_RPN_THRESHOLD = 100;

export interface FmecaSummaryStats {
    subsystems: number;
    functionalFailures: number;
    failureModes: number;
    /** Modes with at least one current control recorded. */
    modesWithControls: number;
    /** Distinct control texts across the project — one PM often covers many modes. */
    distinctControls: number;
    /** Modes with a suggested mitigation recorded. */
    modesWithMitigations: number;
    distinctMitigations: number;
    highRpnModes: number;
    /** Highest scored RPN total, 0 when nothing is scored. */
    maxRpn: number;
}

/** Case and whitespace differences should not make the same task count twice. */
const normalizeAction = (text: string) => text.trim().toLowerCase().replace(/\s+/g, ' ');

/** Every figure in the register Summary. Counted here, never by the AI. */
export function computeSummaryStats(project: Project): FmecaSummaryStats {
    const controls = new Set<string>();
    const mitigations = new Set<string>();
    const stats: FmecaSummaryStats = {
        subsystems: subSystemNames(project).length,
        functionalFailures: 0,
        failureModes: 0,
        modesWithControls: 0,
        distinctControls: 0,
        modesWithMitigations: 0,
        distinctMitigations: 0,
        highRpnModes: 0,
        maxRpn: 0,
    };
    (project.subsystems || []).forEach(sub => {
        (sub.failures || []).forEach(fail => {
            stats.functionalFailures++;
            (fail.modes || []).forEach(mode => {
                stats.failureModes++;
                const control = (mode?.currentControls || '').trim();
                if (control) {
                    stats.modesWithControls++;
                    controls.add(normalizeAction(control));
                }
                const mitigation = (mode?.mitigation || '').trim();
                if (mitigation) {
                    stats.modesWithMitigations++;
                    mitigations.add(normalizeAction(mitigation));
                }
                const total = rpnTotal(mode?.rpn);
                if (typeof total === 'number') {
                    if (total >= HIGH_RPN_THRESHOLD) stats.highRpnModes++;
                    if (total > stats.maxRpn) stats.maxRpn = total;
                }
            });
        });
    });
    stats.distinctControls = controls.size;
    stats.distinctMitigations = mitigations.size;
    return stats;
}

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/** The fixed-format figures block under the description. */
export function buildSummaryStatsBlock(stats: FmecaSummaryStats): string {
    return [
        `Scope: ${plural(stats.subsystems, 'subsystem')} · ${plural(stats.functionalFailures, 'functional failure')} · ${plural(stats.failureModes, 'failure mode')}`,
        `Current controls: ${plural(stats.modesWithControls, 'mode')} covered (${plural(stats.distinctControls, 'distinct task')})`,
        `Suggested mitigations: ${plural(stats.modesWithMitigations, 'mode')} (${plural(stats.distinctMitigations, 'distinct action')})`,
        `High risk: ${plural(stats.highRpnModes, 'mode')} at RPN ≥ ${HIGH_RPN_THRESHOLD}${stats.maxRpn ? ` · max RPN ${stats.maxRpn}` : ''}`,
    ].join('\n');
}

/** Description used until the AI writes one, or when it fails — publishing never waits on AI. */
export function buildFallbackDescription(project: Project): string {
    const name = (project.name || '').trim() || 'Unnamed system';
    const names = subSystemNames(project);
    return names.length ? `${name}: ${names.join(', ')}.` : `${name}.`;
}

/**
 * The register "Summary" column. RCM Studio overwrites the same column once the study
 * becomes a full RCM report, so this is the FMECA-stage summary only.
 */
export function buildSummary(project: Project, description?: string): string {
    const lead = (description || '').trim() || buildFallbackDescription(project);
    return capText(`${lead}\n\n${buildSummaryStatsBlock(computeSummaryStats(project))}`, SUMMARY_MAX_CHARS);
}

const clip = (text: string, max: number) => {
    const t = (text || '').trim().replace(/\s+/g, ' ');
    return t.length > max ? `${t.slice(0, max)}…` : t;
};

export const DESCRIPTION_SYSTEM_PROMPT = `You are a senior reliability engineer writing the opening of the "Summary" entry for an RCM register row.

Write one or two plain sentences, at most 60 words, saying what the system is, what it delivers, and how it is configured (redundancy, main equipment) when the input states it.

Rules:
- Plain text only: no markdown, no bullets, no headings.
- Do not state how many subsystems, functional failures, failure modes, controls or mitigations there are. Those figures are added separately.
- Do not list maintenance actions, controls or mitigations.
- Use only what the input states. Do not invent ratings, equipment or redundancy.
- Output only the sentences — no preamble, no closing remarks.`;

/**
 * Instructions and data in ONE prompt: AIService._directChat only forwards messages[0]
 * for non-chatbot features, so a separate system message would be dropped.
 * The AI sees descriptions only, never counts, so it cannot misstate a figure.
 */
export function buildDescriptionPrompt(project: Project): string {
    const ctx = project.operatingContext;
    const header = [
        `SYSTEM: ${project.name || '(unnamed)'}`,
        project.desc?.trim() ? `PROJECT DESCRIPTION: ${clip(project.desc, 800)}` : '',
        ctx?.summary?.trim() ? `OPERATING CONTEXT: ${clip(ctx.summary, 800)}` : '',
        ctx?.redundancy?.trim() ? `REDUNDANCY: ${clip(ctx.redundancy, 300)}` : '',
        ctx?.dutyCycle?.trim() ? `DUTY CYCLE: ${clip(ctx.dutyCycle, 300)}` : '',
    ].filter(Boolean);
    const subsystems = (project.subsystems || [])
        .filter(s => (s?.name || '').trim())
        .map(s => `- ${s.name.trim()}${s.func?.trim() ? `: ${clip(s.func, 200)}` : ''}`);
    const lines = [...header, '', 'SUBSYSTEMS:', ...subsystems];
    return `${DESCRIPTION_SYSTEM_PROMPT}\n\n${lines.join('\n')}`;
}

/** btoa() is latin1-only, so encode to UTF-8 bytes first (project text may be non-ASCII). */
export function toBase64Utf8(text: string): string {
    const bytes = new TextEncoder().encode(text);
    const CHUNK = 0x8000; // stay under the argument limit of String.fromCharCode
    let binary = '';
    for (let i = 0; i < bytes.length; i += CHUNK) binary += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
    return btoa(binary);
}

/** Same payload as the "Export" button — the normalized project as JSON, base64 encoded. */
export function buildProjectJsonBase64(project: Project): string {
    return toBase64Utf8(JSON.stringify(normalizeProjectDates(project as any)));
}

function capText(text: string, max: number): string {
    if (text.length <= max) return text;
    return text.slice(0, Math.max(0, max - TRUNCATION_SUFFIX.length)) + TRUNCATION_SUFFIX;
}

/**
 * SharePoint rejects these in an attachment name, and a duplicate name on one item is an
 * error rather than a replace — so names are sanitized and deduped before they are sent.
 */
function sanitizeAttachmentName(name: string): string {
    return (name || '').trim().replace(/[~"#%&*:<>?/\\{|}]/g, '-').replace(/\s+/g, ' ');
}

/**
 * Evidence files are stored as plain list attachments alongside the workbook, so the role
 * has to live in the name — `reference-` and `checklist-` are what tells them apart when
 * they are read back. Both kinds are .txt; the extension alone says nothing.
 */
function evidenceAttachment(prefix: string, fileName: string, text: string): RegistryAttachment | null {
    if (!text.trim()) return null;
    const base = sanitizeAttachmentName(fileName) || `${prefix}.txt`;
    const named = base.toLowerCase().endsWith('.txt') ? base : `${base}.txt`;
    // A file already named for its role would otherwise become checklist-checklist-….
    const name = named.toLowerCase().startsWith(`${prefix}-`) || named.toLowerCase().startsWith(`${prefix}_`)
        ? named
        : `${prefix}-${named}`;
    return { name, contentBase64: toBase64Utf8(text) };
}

/**
 * The Settings evidence files as attachments. Exported so the publish modal lists exactly
 * what will be uploaded — building them twice is how the count and the payload drift apart.
 */
export function buildEvidenceAttachments(input: {
    knowledgeFileName?: string;
    knowledgeText?: string;
    checklistFileName?: string;
    checklistText?: string;
}): RegistryAttachment[] {
    return [
        evidenceAttachment('reference', input.knowledgeFileName || '', input.knowledgeText || ''),
        evidenceAttachment('checklist', input.checklistFileName || '', input.checklistText || ''),
    ].filter((a): a is RegistryAttachment => a !== null);
}

/**
 * A date-only value parses as UTC midnight, which SharePoint then renders in the site's own
 * timezone — anywhere behind UTC shows the previous day. Anchoring at midday keeps the
 * calendar date intact on either side of the boundary.
 */
function calendarDateIso(iso: string): string {
    const d = new Date(iso);
    if (Number.isNaN(d.getTime())) return iso;
    return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate(), 12, 0, 0)).toISOString();
}

/** Pure mapping from FMECA project + form values to the registry flow payload. */
export function buildRegisterPayload(project: Project, opts: BuildRegisterPayloadOptions): RcmRegisterPayload {
    const summary = opts.summary.trim() || buildSummary(project);
    const cols = REGISTER_LIST.columns;

    const attachments: RegistryAttachment[] = [
        { name: sanitizeAttachmentName(opts.fileName), contentBase64: opts.fileContentBase64 },
        { name: sanitizeAttachmentName(opts.jsonFileName), contentBase64: opts.jsonContentBase64 },
        ...(opts.extraAttachments || []),
    ].filter(a => !!a.name && !!a.contentBase64);

    const seen = new Set<string>();
    const unique = attachments.filter(a => {
        const key = a.name.toLowerCase();
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
    });

    return {
        v: 1,
        site: REGISTER_LIST.site,
        list: REGISTER_LIST.list,
        fields: {
            [cols.system]: project.name || '',
            [cols.subSystems]: buildSubSystemsList(project),
            [cols.startDate]: calendarDateIso(tryIso(opts.startDate) || projectStartIso(project)),
            [cols.status]: opts.status,
            [cols.summary]: capText(summary, SUMMARY_MAX_CHARS),
        },
        person: opts.engineerEmail.trim() ? { column: cols.engineerName, email: opts.engineerEmail.trim() } : undefined,
        autoNumber: { column: cols.rcmInternalNumber, prefix: 'RCM' },
        attachments: unique,
    };
}

/**
 * POSTs one request to the Power Automate flow backing the SharePoint RCM register and
 * returns its parsed JSON reply. Every action (create / list / fetch) shares this URL;
 * the flow switches on `action`.
 */
async function postToFlow(flowUrl: string, body: unknown): Promise<any> {
    if (!flowUrl.trim()) throw new Error('Set the RCM Register flow URL in Settings.');

    // Body is JSON, but the Content-Type is text/plain on purpose: it keeps this a CORS
    // "simple request" so the browser skips the preflight. Power Automate's HTTP trigger
    // does not answer OPTIONS, so an application/json POST never reaches the flow.
    // The flow must therefore parse the body with json(triggerBody()).
    const res = await fetch(flowUrl.trim(), {
        method: 'POST',
        headers: { 'Content-Type': 'text/plain;charset=UTF-8' },
        body: JSON.stringify(body),
    });

    if (!res.ok) {
        const text = await res.text().catch(() => '');
        throw new Error(`RCM Register error: HTTP ${res.status} ${res.statusText}. ${text}`);
    }

    const raw = await res.text();
    try { return JSON.parse(raw); } catch {
        throw new Error(`RCM Register error: flow reply was not JSON. Raw response: ${raw}`);
    }
}

/**
 * POSTs one row to the Power Automate flow backing the SharePoint RCM register.
 * The flow — not this app — computes the RCM internal number and returns it.
 */
export async function publishToRcmRegister(flowUrl: string, payload: RcmRegisterPayload): Promise<RcmRegisterResult> {
    const parsed = await postToFlow(flowUrl, payload);
    // `number` is what the registry flow returns; `rcmInternalNumber` was the older flow's name.
    const rcmInternalNumber = String(parsed?.number ?? parsed?.rcmInternalNumber ?? '').trim();
    const itemId = Number(parsed?.itemId);
    if (!rcmInternalNumber || !Number.isFinite(itemId)) {
        throw new Error(`RCM Register error: flow reply missing number or itemId. Raw response: ${JSON.stringify(parsed)}`);
    }
    // The registry flow is list-agnostic and returns no link, so build the row URL here.
    const itemLink = String(parsed?.itemLink ?? '')
        || `${payload.site}/Lists/${encodeURIComponent(payload.list)}/DispForm.aspx?ID=${itemId}`;
    return { rcmInternalNumber, itemId, itemLink };
}

const C = REGISTER_LIST.columns;

/** Columns the picker needs. The Person column only yields an email when expanded. */
const REGISTER_SELECT = `ID,${C.rcmInternalNumber},${C.system},${C.status},${C.startDate},${C.engineerName}/Title,${C.engineerName}/EMail`;

/**
 * Lists the register rows so the user can pick one to open. The reader replies with raw
 * SharePoint fields under `{ items: [...] }`; a bare array or `{ value: [...] }` is accepted
 * too, since that is what a "Get items" style flow returns.
 */
export async function listRegisterProjects(readerUrl: string): Promise<RcmRegisterRow[]> {
    const parsed = await postToFlow(readerUrl, {
        action: 'list',
        site: REGISTER_LIST.site,
        list: REGISTER_LIST.list,
        select: REGISTER_SELECT,
        expand: C.engineerName,
        orderBy: 'ID desc',
        top: 500,
    });
    const rows = Array.isArray(parsed) ? parsed
        : Array.isArray(parsed?.items) ? parsed.items
        : Array.isArray(parsed?.value) ? parsed.value
        : null;
    if (!rows) {
        throw new Error(`RCM Register error: expected a list of rows. Raw response: ${JSON.stringify(parsed)}`);
    }
    return rows
        .map((row: any): RcmRegisterRow => {
            const person = row?.[C.engineerName];
            return {
                itemId: Number(row?.ID ?? row?.Id ?? row?.itemId),
                rcmInternalNumber: String(row?.[C.rcmInternalNumber] ?? '').trim(),
                system: String(row?.[C.system] ?? '').trim(),
                status: String(row?.[C.status] ?? '').trim(),
                engineerName: String(person?.EMail || person?.Title || '').trim(),
                startDate: String(row?.[C.startDate] ?? '').trim(),
                jsonFileName: '',
            };
        })
        .filter(row => Number.isFinite(row.itemId));
}

/** Decodes base64 back to text as UTF-8 — the inverse of `toBase64Utf8`. */
export function fromBase64Utf8(base64: string): string {
    const binary = atob(base64.replace(/^data:[^,]*,/, '').trim());
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
    return new TextDecoder().decode(bytes);
}

/**
 * Downloads the FMECA JSON attachment of one register row through the flow and parses it.
 * Validation that the parsed object really is an FMECA project stays with the caller, which
 * already owns that guard for file imports.
 */
export async function fetchRegisterProjectJson(readerUrl: string, itemId: number): Promise<any> {
    const parsed = await postToFlow(readerUrl, {
        action: 'fetch',
        site: REGISTER_LIST.site,
        list: REGISTER_LIST.list,
        itemId,
        // Publishing attaches both the workbook and the project JSON; match on the suffix so
        // the reader picks the right one without the app knowing the exact file name.
        fileNameEndsWith: '.json',
    });
    const base64 = String(parsed?.contentBase64 ?? parsed?.fileContentBase64 ?? '').trim();
    if (!base64) {
        throw new Error(`RCM Register error: row ${itemId} returned no FMECA JSON attachment. Raw response: ${JSON.stringify(parsed)}`);
    }
    let text: string;
    try { text = fromBase64Utf8(base64); } catch {
        throw new Error(`RCM Register error: the attachment of row ${itemId} is not valid base64.`);
    }
    try { return JSON.parse(text); } catch {
        throw new Error(`RCM Register error: the attachment of row ${itemId} is not valid JSON.`);
    }
}
