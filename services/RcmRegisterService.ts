// SharePoint's "Multiple lines of text" (plain text, no append) holds 63,999 characters.
// Stay just under it — the earlier 2,000 cap was ours, not the list's, and truncated summaries.
const SUMMARY_MAX_CHARS = 60000;
const TRUNCATION_SUFFIX = '…(truncated)';

/** One file to attach to the new row. The flow loops over these, type-agnostic. */
export interface RegistryAttachment {
    name: string;               // attachment file name, unique within the row
    contentBase64: string;      // raw base64, no data: prefix
}

/**
 * Payload for the generic "SharePoint Registry" flow. The flow is list-agnostic: the site,
 * the list and the column names all travel in the request, so this mapping belongs to the
 * app. `fields` keys are SharePoint internal names (see REGISTER_LIST.columns).
 *
 * The flow generates the RCM internal number itself — it reads the last one matching
 * `autoNumber` and increments — because two engineers publishing at once would otherwise
 * both read the same value. It resolves `person.email` to a site-user id, since a Person
 * column cannot be set from an email over REST.
 */
export interface RcmRegisterPayload {
    v: 1;
    site: string;
    list: string;
    fields: Record<string, string>;
    person?: { column: string; email: string };
    autoNumber?: { column: string; prefix: string };
    attachments: RegistryAttachment[];
}

export interface RcmRegisterResult {
    rcmInternalNumber: string;  // generated BY THE FLOW, e.g. RCM-2026-02
    itemId: number;
    itemLink: string;
}

/** One register row as shown in the "open from SharePoint" picker. */
export interface RcmRegisterRow {
    itemId: number;
    rcmInternalNumber: string;
    system: string;
    status: string;
    engineerName: string;
    startDate: string;
    /** Name of the FMECA JSON attachment, when the flow reports it. */
    jsonFileName: string;
}

/**
 * Where the register lives, for the generic SharePoint Reader flow. That flow is
 * list-agnostic — it takes the site and list per request and returns raw SharePoint
 * fields — so the app owns this mapping rather than the flow.
 *
 * Internal names come from the reader's own `schema` action; note the RCM internal
 * number is stored in the built-in `Title` column, not a custom one.
 */
export const REGISTER_LIST = {
    site: 'https://oxyinc.sharepoint.com/sites/AIProduction',
    list: 'RCM List',
    columns: {
        rcmInternalNumber: 'Title',
        system: 'System',
        subSystems: 'Sub_x002d_Systems',
        startDate: 'StartDate',
        engineerName: 'EngineerName',   // Person column — needs $expand to read the email
        status: 'Status',
        // Shown as "Summary" in the list. The internal name was fixed when the column was
        // created as "Summary of Actions" and cannot change. RCM Studio overwrites it.
        summary: 'SummaryofActions',
    },
} as const;

